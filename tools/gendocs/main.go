package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/doc"
	"go/parser"
	"go/printer"
	"go/token"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"
)

const module = "github.com/prettylittlelies/cry"

var skip = []string{"tests", "tools", "examples", "internal", ".git"}

type page struct {
	importPath string
	file       string
	pkg        *doc.Package
	fset       *token.FileSet
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gendocs <module root> <output dir>")
		os.Exit(2)
	}
	root, out := os.Args[1], os.Args[2]
	pages, err := collect(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.MkdirAll(out, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	for _, p := range pages {
		if err := os.WriteFile(filepath.Join(out, p.file), render(p), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	if err := os.WriteFile(filepath.Join(out, "README.md"), index(pages), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("documented %d packages\n", len(pages))
}

func collect(root string) ([]page, error) {
	var pages []page
	err := filepath.WalkDir(root, func(dir string, d fs.DirEntry, err error) error {
		if err != nil || !d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(root, dir)
		rel = filepath.ToSlash(rel)
		if slices.ContainsFunc(skip, func(s string) bool { return rel == s || strings.HasPrefix(rel, s+"/") || strings.Contains(rel, "/"+s) }) {
			return filepath.SkipDir
		}
		p, err := load(dir, rel)
		if err != nil || p == nil {
			return err
		}
		pages = append(pages, *p)
		return nil
	})
	slices.SortFunc(pages, func(a, b page) int { return strings.Compare(a.importPath, b.importPath) })
	return pages, err
}

func load(dir, rel string) (*page, error) {
	fset := token.NewFileSet()
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []*ast.File
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		if f.Name.Name == "main" {
			return nil, nil
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return nil, nil
	}
	importPath := module
	file := "cry.md"
	if rel != "." {
		importPath = path.Join(module, rel)
		file = strings.ReplaceAll(rel, "/", "-") + ".md"
	}
	pkg, err := doc.NewFromFiles(fset, files, importPath)
	if err != nil {
		return nil, err
	}
	return &page{importPath: importPath, file: file, pkg: pkg, fset: fset}, nil
}

func source(fset *token.FileSet, node any) string {
	var b bytes.Buffer
	if fn, ok := node.(*ast.FuncDecl); ok {
		cp := *fn
		cp.Body, cp.Doc = nil, nil
		node = &cp
	}
	(&printer.Config{Mode: printer.UseSpaces | printer.TabIndent, Tabwidth: 8}).Fprint(&b, fset, node)
	return b.String()
}

func anchor(s string) string {
	return strings.ToLower(strings.NewReplacer(".", "", " ", "-", "(", "", ")", "", "*", "").Replace(s))
}

func render(p page) []byte {
	var b bytes.Buffer
	pkg := p.pkg
	fmt.Fprintf(&b, "# %s\n\n```go\nimport \"%s\"\n```\n\n", pkg.Name, p.importPath)
	if len(pkg.Types)+len(pkg.Funcs) > 0 {
		b.WriteString("## Index\n\n")
		for _, f := range pkg.Funcs {
			fmt.Fprintf(&b, "- [func %s](#func-%s)\n", f.Name, anchor(f.Name))
		}
		for _, t := range pkg.Types {
			fmt.Fprintf(&b, "- [type %s](#type-%s)\n", t.Name, anchor(t.Name))
		}
		b.WriteString("\n")
	}
	section := func(title string, values []*doc.Value) {
		if len(values) == 0 {
			return
		}
		fmt.Fprintf(&b, "## %s\n\n", title)
		for _, v := range values {
			fmt.Fprintf(&b, "```go\n%s\n```\n\n", source(p.fset, v.Decl))
		}
	}
	section("Constants", pkg.Consts)
	section("Variables", pkg.Vars)
	if len(pkg.Funcs) > 0 {
		b.WriteString("## Functions\n\n")
		for _, f := range pkg.Funcs {
			fmt.Fprintf(&b, "### func %s\n\n```go\n%s\n```\n\n", f.Name, source(p.fset, f.Decl))
		}
	}
	if len(pkg.Types) > 0 {
		b.WriteString("## Types\n\n")
		for _, t := range pkg.Types {
			fmt.Fprintf(&b, "### type %s\n\n```go\n%s\n```\n\n", t.Name, source(p.fset, t.Decl))
			for _, v := range append(t.Consts, t.Vars...) {
				fmt.Fprintf(&b, "```go\n%s\n```\n\n", source(p.fset, v.Decl))
			}
			for _, f := range t.Funcs {
				fmt.Fprintf(&b, "#### func %s\n\n```go\n%s\n```\n\n", f.Name, source(p.fset, f.Decl))
			}
			for _, m := range t.Methods {
				fmt.Fprintf(&b, "#### func (%s) %s\n\n```go\n%s\n```\n\n", m.Recv, m.Name, source(p.fset, m.Decl))
			}
		}
	}
	return b.Bytes()
}

func index(pages []page) []byte {
	var b bytes.Buffer
	b.WriteString("# API reference\n\nGenerated by `go run ./tools/gendocs . docs` from the exported API of each package.\n\n| Package | Types | Functions |\n| --- | --- | --- |\n")
	for _, p := range pages {
		methods := len(p.pkg.Funcs)
		for _, t := range p.pkg.Types {
			methods += len(t.Funcs) + len(t.Methods)
		}
		fmt.Fprintf(&b, "| [`%s`](%s) | %d | %d |\n", strings.TrimPrefix(p.importPath, module+"/"), p.file, len(p.pkg.Types), methods)
	}
	return b.Bytes()
}
